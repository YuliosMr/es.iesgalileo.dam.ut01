public class Calculadora {
	
	/*
	 * Suma los dos valores enteros
	 * @param sumando1
	 * @param sumando2
	 * @return La suma de ambos
	 */
	
	public static int sumar(int sumando1, int sumando2) {
		return sumando1 + sumando2;
		
	}
	/*
	 * Resta y bla bla bla
	 * @param restando1
	 * @param restando2
	 * @return La resta de ambos
	 */
	
	public static int rest (int restando1, int restando2) {
		return restando1 - restando2;
	}
	/*
	 * multiplica, que mas hace?
	 * @param operando1
	 * @param operando2
	 * @return La multiplicacion de ambos
	 */
	
	public static int multi(int operando1, int operando2) {
		return operando1 * operando2;
	}

}
